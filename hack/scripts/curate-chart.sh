#!/usr/bin/env bash
# Curate the freshly Kubebuilder-generated chart in dist/chart to the
# reviewed packaging contract (docs/development.md, Packaging):
#   - restore the committed curated values.yaml when the plugin
#     regenerated a fresh one;
#   - move the rendered image values to the top-level
#     controllerImage.{repository,tag} and restore the canonical
#     [/manager, operator] command;
#   - drop the plugin's re-scaffolded unpinned CI workflow.
set -euo pipefail
cd "$(dirname "$0")/../.."

chart=dist/chart

# The plugin regenerates values.yaml from its own template when the
# curated file is missing; the curated values are the reviewed contract
# (every referenced key declared, fixed fullnameOverride).
if grep -qE '^  image:' "$chart/values.yaml"; then
	if git ls-files --error-unmatch "$chart/values.yaml" >/dev/null 2>&1; then
		echo "NOTE: $chart/values.yaml was regenerated by the plugin; restoring the committed curated values." >&2
		git checkout -- "$chart/values.yaml"
	else
		echo "ERROR: $chart/values.yaml was regenerated by the plugin and no committed curated version exists." >&2
		echo "       Commit the curated values.yaml first (see docs/development.md, Packaging)." >&2
		exit 1
	fi
fi

# The plugin renders the image from manager.image.{repository,tag} and
# the command as [/manager] with the operator subcommand in manager.args.
# The reviewed contract keeps image values under the top-level
# controllerImage.{repository,tag} (whole values, see test/support/helm)
# and the canonical command [/manager, operator]. The deletion keeps the
# rewrite idempotent on an already curated template (operator belongs to
# the command, never to args).
sed -i \
	-e 's/\.Values\.manager\.image\./\.Values.controllerImage./g' \
	-e '/^        - operator$/d' \
	-e 's|^        - /manager$|        - /manager\n        - operator|' \
	"$chart/templates/manager/manager.yaml"

# The plugin re-scaffolds an unpinned CI workflow on every run; this PoC
# ships no release/CI matrix, so the curated state carries no
# .github/workflows/test-chart.yml.
rm -f .github/workflows/test-chart.yml
rmdir .github/workflows .github 2>/dev/null || true
