// These tests validate the CRD YAML generated by `make manifests` (from the
// kubebuilder markers in this package) against the approved contract in
// docs/design/poc-contract.md §4/§5. They intentionally read the generated
// artifacts instead of the markers, so marker drift cannot silently change
// the shipped schema. The Makefile runs `make manifests` before the tests.

const (
	deviceCRDFile     = "infrastructure.platform.opendatahub.io_hardwaredevices.yaml"
	discoveryCRDFile  = "infrastructure.platform.opendatahub.io_hardwarediscoveries.yaml"
	quantityPattern   = `^(\+|-)?(([0-9]+(\.[0-9]*)?)|(\.[0-9]+))(([KMGTPE]i)|[numkMGTPE]|([eE](\+|-)?(([0-9]+(\.[0-9]*)?)|(\.[0-9]+))))?$`
	durationPattern   = `^([0-9]+(s|m|h))+$`
	singletonNameRule = "self.metadata.name == 'cluster'"
)

func crdBaseDir(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	return filepath.Join(dir, "..", "..", "..", "config", "crd", "bases")
}

// loadCRD reads a generated CRD. A missing file is a hard failure: the tests
// document that `make test` (which depends on `make manifests`) is the entry
// point, and silently skipping would hide missing generated state.
func loadCRD(t *testing.T, filename string) map[string]any {
	t.Helper()
	g := NewWithT(t)

	path := filepath.Join(crdBaseDir(t), filename)
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		t.Fatalf("generated CRD %s not found under config/crd/bases: run `make manifests` first", filename)
	}
	g.Expect(err).NotTo(HaveOccurred())

	var crd map[string]any
	g.Expect(yaml.Unmarshal(raw, &crd)).To(Succeed())
	return crd
}

// version returns the single served version object of a CRD.
func version(t *testing.T, g *WithT, crd map[string]any) map[string]any {
	t.Helper()
	versions := crd["spec"].(map[string]any)["versions"].([]any)
	g.Expect(versions).To(HaveLen(1), "exactly one version is served")
	v := versions[0].(map[string]any)
	g.Expect(v["name"]).To(Equal("v1alpha1"))
	g.Expect(v["served"]).To(BeTrue())
	g.Expect(v["storage"]).To(BeTrue(), "v1alpha1 must be the only storage version")
	return v
}

// rootSchema returns the root OpenAPI schema of a version.
func rootSchema(t *testing.T, v map[string]any) map[string]any {
	t.Helper()
	return v["schema"].(map[string]any)["openAPIV3Schema"].(map[string]any)
}

// field navigates node.properties.<f1>.properties.<f2>... below a schema
// node. Pass the root openAPIV3Schema to start at the top level.
func field(t *testing.T, node map[string]any, fields ...string) map[string]any {
	t.Helper()
	current := node
	for _, f := range fields {
		propsMap, ok := current["properties"].(map[string]any)
		if !ok {
			t.Fatalf("schema node has no properties (navigating %v, failed at %q)", fields, f)
		}
		next, ok := propsMap[f].(map[string]any)
		if !ok {
			t.Fatalf("schema field %v not found (failed at %q)", fields, f)
		}
		current = next
	}
	return current
}

// items returns the items schema of an array node.
func items(t *testing.T, node map[string]any) map[string]any {
	t.Helper()
	item, ok := node["items"].(map[string]any)
	if !ok {
		t.Fatalf("array node has no items schema")
	}
	return item
}

// validationRules returns the x-kubernetes-validations rule strings of a
// schema node.
func validationRules(t *testing.T, node map[string]any) []string {
	t.Helper()
	raw, ok := node["x-kubernetes-validations"].([]any)
	if !ok {
		return nil
	}
	rules := make([]string, 0, len(raw))
	for _, r := range raw {
		rules = append(rules, r.(map[string]any)["rule"].(string))
	}
	return rules
}

func TestHardwareDeviceCRDContract(t *testing.T) {
	g := NewWithT(t)
	crd := loadCRD(t, deviceCRDFile)
	spec := crd["spec"].(map[string]any)

	t.Run("names", func(t *testing.T) {
		g := NewWithT(t)
		names := spec["names"].(map[string]any)
		g.Expect(names["kind"]).To(Equal("HardwareDevice"))
		g.Expect(names["singular"]).To(Equal("hardwaredevice"))
		g.Expect(names["plural"]).To(Equal("hardwaredevices"))
		g.Expect(names["shortNames"]).To(ConsistOf("hwdev", "hw"))
		g.Expect(names["categories"]).To(ConsistOf("odh", "platform", "all"))
	})

	t.Run("scope and subresource", func(t *testing.T) {
		g := NewWithT(t)
		g.Expect(spec["scope"]).To(Equal("Cluster"))
		v := version(t, g, crd)
		subresources, ok := v["subresources"].(map[string]any)
		g.Expect(ok).To(BeTrue(), "status subresource must be declared")
		g.Expect(subresources).To(HaveKey("status"))
	})

	t.Run("printer columns", func(t *testing.T) {
		g := NewWithT(t)
		v := version(t, g, crd)
		cols := v["additionalPrinterColumns"].([]any)
		byName := map[string]string{}
		for _, c := range cols {
			col := c.(map[string]any)
			byName[col["name"].(string)] = col["jsonPath"].(string)
		}
		g.Expect(byName).To(MatchKeys(IgnoreExtras, Keys{
			"Class":     Equal(`.spec.class`),
			"Model":     Equal(`.status.model`),
			"Memory":    Equal(`.status.memory`),
			"Node":      Equal(`.spec.host.name`),
			"Plane":     Equal(`.status.allocationPlane`),
			"Collected": Equal(`.status.collectedAt`),
			"Age":       Equal(`.metadata.creationTimestamp`),
		}))
	})

	schema := rootSchema(t, version(t, g, crd))

	t.Run("spec validation", func(t *testing.T) {
		g := NewWithT(t)
		specSchema := field(t, schema, "spec")

		class := field(t, specSchema, "class")
		g.Expect(class["enum"]).To(ConsistOf("accelerator"))
		g.Expect(validationRules(t, class)).To(ContainElement("self == oldSelf"))

		identity := field(t, specSchema, "identity", "id")
		g.Expect(identity["minLength"]).To(BeNumerically("==", 1))
		g.Expect(identity["maxLength"]).To(BeNumerically("==", 63))
		g.Expect(validationRules(t, identity)).To(ContainElement("self == oldSelf"))

		hostUID := field(t, specSchema, "host", "uid")
		g.Expect(hostUID["type"]).To(Equal("string"))
		g.Expect(hostUID["minLength"]).To(BeNumerically("==", 1))
		g.Expect(validationRules(t, hostUID)).To(ContainElement("self == oldSelf"))

		specRules := validationRules(t, specSchema)
		g.Expect(specRules).To(ContainElement(
			"(has(self.source.dra) ? 1 : 0) + (has(self.source.simulator) ? 1 : 0) == 1"),
			"exactly-one source locator CEL rule")
		g.Expect(specRules).To(ContainElement(
			"!has(self.source.simulator) || self.source.simulator.id == self.identity.id"),
			"simulator id must match identity.id")

		source := field(t, specSchema, "source")
		driver := field(t, source, "dra", "driver")
		g.Expect(driver["pattern"]).To(Equal(`^[a-z0-9]([-a-z0-9]*[a-z0-9])?(\.[a-z0-9]([-a-z0-9]*[a-z0-9])?)*$`))
		for _, f := range []string{"pool", "device"} {
			s := field(t, source, "dra", f)
			g.Expect(s["minLength"]).To(BeNumerically("==", 1))
		}
		for _, f := range []string{"namespace", "configMap", "id"} {
			s := field(t, source, "simulator", f)
			g.Expect(s["minLength"]).To(BeNumerically("==", 1))
		}
	})

	t.Run("status validation", func(t *testing.T) {
		g := NewWithT(t)
		statusSchema := field(t, schema, "status")

		plane := field(t, statusSchema, "allocationPlane")
		g.Expect(plane["enum"]).To(ConsistOf("classic", "dra"))

		memory := field(t, statusSchema, "memory")
		g.Expect(memory["pattern"]).To(Equal(quantityPattern),
			"resource.Quantity must carry the canonical Quantity pattern")

		conditions := field(t, statusSchema, "conditions")
		g.Expect(conditions["x-kubernetes-list-type"]).To(Equal("map"))
	})
}

func TestHardwareDiscoveryCRDContract(t *testing.T) {
	g := NewWithT(t)
	crd := loadCRD(t, discoveryCRDFile)
	spec := crd["spec"].(map[string]any)

	t.Run("names", func(t *testing.T) {
		g := NewWithT(t)
		names := spec["names"].(map[string]any)
		g.Expect(names["kind"]).To(Equal("HardwareDiscovery"))
		g.Expect(names["plural"]).To(Equal("hardwarediscoveries"))
		g.Expect(names).NotTo(HaveKey("shortNames"), "the singleton has no short names")
		g.Expect(names).NotTo(HaveKey("categories"))
	})

	t.Run("scope and subresource", func(t *testing.T) {
		g := NewWithT(t)
		g.Expect(spec["scope"]).To(Equal("Cluster"))
		v := version(t, g, crd)
		subresources, ok := v["subresources"].(map[string]any)
		g.Expect(ok).To(BeTrue(), "status subresource must be declared")
		g.Expect(subresources).To(HaveKey("status"))
	})

	t.Run("singleton name enforced by root CEL", func(t *testing.T) {
		g := NewWithT(t)
		schema := rootSchema(t, version(t, g, crd))
		g.Expect(validationRules(t, schema)).To(ContainElement(singletonNameRule))
	})

	schema := rootSchema(t, version(t, g, crd))

	t.Run("spec validation and defaults", func(t *testing.T) {
		g := NewWithT(t)
		specSchema := field(t, schema, "spec")

		class := field(t, specSchema, "class")
		g.Expect(class["enum"]).To(ConsistOf("accelerator"))
		g.Expect(validationRules(t, class)).To(ContainElement("self == oldSelf"))

		nodeSelector := field(t, specSchema, "nodeSelector")
		g.Expect(nodeSelector["type"]).To(Equal("object"))

		for _, f := range []string{"maxStale", "rescanPeriod", "nodeGracePeriod"} {
			d := field(t, specSchema, f)
			g.Expect(d["type"]).To(Equal("string"), f)
			g.Expect(d["pattern"]).To(Equal(durationPattern), f+" pattern")
		}
		g.Expect(field(t, specSchema, "maxStale")["default"]).To(Equal("10m"))
		g.Expect(field(t, specSchema, "rescanPeriod")["default"]).To(Equal("5m"))
		g.Expect(field(t, specSchema, "nodeGracePeriod")["default"]).To(Equal("15m"))

		draEnabled := field(t, specSchema, "sources", "dra", "enabled")
		g.Expect(draEnabled["default"]).To(Equal(true))
		allowList := field(t, specSchema, "sources", "dra", "driverAllowList")
		g.Expect(allowList["default"]).To(Equal([]any{nvidiaDriver}))

		simEnabled := field(t, specSchema, "sources", "simulator", "enabled")
		g.Expect(simEnabled["default"]).To(Equal(false))
		simConfig := field(t, specSchema, "sources", "simulator")
		g.Expect(validationRules(t, simConfig)).To(ContainElement(
			"!(has(self.enabled) && self.enabled) || (has(self.namespace) && size(self.namespace) > 0)"),
			"namespace required when the simulator source is enabled")
		simPrefix := field(t, specSchema, "sources", "simulator", "configMapPrefix")
		g.Expect(simPrefix["default"]).To(Equal("topology"))
	})

	t.Run("status validation", func(t *testing.T) {
		g := NewWithT(t)
		statusSchema := field(t, schema, "status")

		summaries := field(t, statusSchema, "nodeSummaries")
		g.Expect(summaries["x-kubernetes-list-type"]).To(Equal("map"))
		g.Expect(summaries["x-kubernetes-list-map-keys"]).To(Equal([]any{"name"}))

		summaryItem := items(t, summaries)
		outcome := field(t, summaryItem, "outcome")
		g.Expect(outcome["enum"]).To(ConsistOf("Success", "Unknown"))
		plane := field(t, summaryItem, "plane")
		g.Expect(plane["enum"]).To(ConsistOf("classic", "dra"))
	})
}
